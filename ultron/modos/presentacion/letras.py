def _base(c: str) -> str:
    if c.upper() in _F:
        return c.upper()
    sin = unicodedata.normalize("NFKD", c).encode("ascii", "ignore").decode().upper()
    return sin if sin in _F else " "


def grandes(texto: str, lleno: str = "█") -> list[str]:
    """Cinco líneas con el texto en letras grandes (cada píxel ocupa dos columnas)."""
    filas = [""] * 5
    for c in texto:
        patron = _F[_base(c)]
        for i in range(5):
            filas[i] += "".join(lleno * 2 if p == "#" else "  " for p in patron[i]) + "  "
    return [f.rstrip() for f in filas]


def ancho(texto: str) -> int:
    return max((len(f) for f in grandes(texto)), default=0)
